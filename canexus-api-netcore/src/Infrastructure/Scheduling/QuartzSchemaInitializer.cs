
using Infrastructure.Shared.Options;
using Microsoft.Extensions.Hosting;
using Microsoft.Extensions.Logging;
using Microsoft.Extensions.Options;
using MySqlConnector;

namespace Infrastructure.Scheduling;

/// <summary>
/// Quartz 集群存储初始化（P1-A4）：确保 MySQL 中 QRTZ_* 11 张集群表存在（幂等），
/// 作为宿主服务注册且先于 <c>AddQuartzHostedService</c> 启动——否则 JobStoreTX 在调度器启动时即连接失败。
/// <para>本服务器默认存储引擎为 MyISAM（无行锁语义），QRTZ_LOCKS 等表显式 ENGINE=InnoDB 以保证集群锁有效。</para>
/// </summary>
public sealed class QuartzSchemaInitializer(IOptions<DatabaseOption> database, ILogger<QuartzSchemaInitializer> logger) : IHostedService
{
    /// <summary>
    /// Quartz.NET 3.x MySQL 集群表结构（11 表 + 官方索引，转 InnoDB + utf8mb4）。
    /// <para>以分号分隔逐条执行；表存在性由调用方以 information_schema 判定，本脚本仅负责建表建索引。</para>
    /// </summary>
    private const string SchemaDdl =
        """
