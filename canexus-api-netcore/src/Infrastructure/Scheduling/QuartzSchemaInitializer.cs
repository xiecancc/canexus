        """;

    /// <summary>
    /// 确保 QRTZ_* 集群表存在（幂等）：QRTZ_LOCKS 已存在即视为 schema 已就绪，直接返回。
    /// <para>供宿主启动与集群集成测试共用；以 information_schema 判定（DbMaintenance.IsAnyTable 对新建表不可靠）。</para>
    /// </summary>
    /// <param name="connectionString">数据库连接串。</param>
    /// <param name="cancellationToken">取消令牌。</param>
    public static async Task EnsureSchemaAsync(string connectionString, CancellationToken cancellationToken = default)
    {
        await using var connection = new MySqlConnection(connectionString);
        await connection.OpenAsync(cancellationToken);

        await using (var probe = connection.CreateCommand())
        {
            probe.CommandText =
                "SELECT COUNT(*) FROM information_schema.TABLES WHERE TABLE_SCHEMA = DATABASE() AND TABLE_NAME = 'QRTZ_LOCKS'";
            var exists = Convert.ToInt32(await probe.ExecuteScalarAsync(cancellationToken)) > 0;
            if (exists)
            {
                return;
            }
        }

        foreach (var statement in SchemaDdl.Split(';', StringSplitOptions.RemoveEmptyEntries | StringSplitOptions.TrimEntries))
        {
            await using var command = connection.CreateCommand();
            command.CommandText = statement;
            await command.ExecuteNonQueryAsync(cancellationToken);
        }
    }

    /// <inheritdoc />
    /// <remarks>建表失败即抛（fail-fast）：QRTZ_ 表缺失时调度器启动必然失败，尽早暴露而非带病运行。</remarks>
    public async Task StartAsync(CancellationToken cancellationToken)
    {
        try
        {
            await EnsureSchemaAsync(database.Value.ConnectionString, cancellationToken);
            logger.LogInformation("Quartz 集群存储：QRTZ_ 表已就绪");
        }
        catch (Exception exception)
        {
            logger.LogError(exception, "Quartz 集群存储初始化失败：QRTZ_ 表无法确保存在，调度器将无法启动");
            throw;
        }
    }

    /// <inheritdoc />
    public Task StopAsync(CancellationToken cancellationToken) => Task.CompletedTask;
}
